CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone VARCHAR(20) NOT NULL UNIQUE,
    role VARCHAR(12) NOT NULL CHECK (role IN ('CUSTOMER', 'MERCHANT')),
    display_name VARCHAR(100) NOT NULL,
    pin_hash VARCHAR(100) NOT NULL,
    merchant_code VARCHAR(24) UNIQUE,
    failed_pin_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE wallets (
    account_id BIGINT PRIMARY KEY REFERENCES accounts(id),
    balance_minor BIGINT NOT NULL DEFAULT 0 CHECK (balance_minor >= 0),
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE payment_intents (
    id VARCHAR(36) PRIMARY KEY,
    payer_id BIGINT NOT NULL REFERENCES accounts(id),
    payee_id BIGINT NOT NULL REFERENCES accounts(id),
    amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
    status VARCHAR(12) NOT NULL CHECK (status IN ('PENDING', 'SETTLED', 'EXPIRED', 'CANCELLED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    settled_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_payment_intents_payer ON payment_intents(payer_id, created_at);

CREATE TABLE ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id VARCHAR(36) NOT NULL,
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    delta_minor BIGINT NOT NULL CHECK (delta_minor <> 0),
    entry_type VARCHAR(16) NOT NULL CHECK (entry_type IN ('DEBIT', 'CREDIT', 'TEST_FUND')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(operation_id, account_id)
);

CREATE TABLE inbound_messages (
    message_id VARCHAR(100) PRIMARY KEY,
    phone VARCHAR(20) NOT NULL,
    body_sha256 VARCHAR(64) NOT NULL,
    response_text VARCHAR(500),
    received_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
